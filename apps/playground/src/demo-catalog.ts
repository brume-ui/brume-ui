export function getDemoFeature(id: string): DemoFeature | undefined {
  return DEMO_FEATURES.find((feature) => feature.id === id);
}
export function filterDemoFeatures(query: string, category: DemoCategory | 'all'): DemoFeature[] {
  const term = query.trim().toLocaleLowerCase();
  return DEMO_FEATURES.filter(
    (feature) =>
      (category === 'all' || feature.category === category) &&
      [feature.id, feature.title, feature.summary, feature.expected, ...feature.steps]
        .join(' ')
        .toLocaleLowerCase()
        .includes(term),
  );
}
