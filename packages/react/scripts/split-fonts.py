#!/usr/bin/env python3
"""Split jf-openhuninn into unicode-range woff2 subsets and emit src/fonts.css.

Offline and deterministic. Run manually when the source font changes:
  uv run --with fonttools --with brotli python scripts/split-fonts.py path/to/jf-openhuninn-2.1.ttf
Requires fonttools + brotli. The output (fonts/*.woff2, src/fonts.css) is committed,
so the normal build never needs this script or the network.

Chunking: characters are ordered by Big5 position (level 1 = the ~5400 most
common Traditional Chinese characters, then level 2), so everyday text pulls in
only a few chunks. Anything outside Big5 follows in codepoint order.
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
if len(sys.argv) < 2:
    sys.exit("usage: split-fonts.py <jf-openhuninn-2.1.ttf>  (from github.com/justfont/open-huninn-font releases)")
SRC = Path(sys.argv[1])
OUT = ROOT / "fonts"
CHUNK = 250
FAMILY = "jf-openhuninn"

cmap = set(TTFont(str(SRC)).getBestCmap().keys())
cmap.discard(0)

def big5_key(cp):
    try:
        b = chr(cp).encode("big5")
    except UnicodeEncodeError:
        return None
    return int.from_bytes(b, "big") if len(b) == 2 else None

# Dedicated first chunk: CJK and fullwidth punctuation plus a few common symbols, so a
# typical sentence does not pull a chunk full of rare hanzi just for "，" or "「".
PUNCT_RANGES = [(0x3000, 0x303F), (0xFF00, 0xFFEF), (0x2010, 0x2027), (0xB7, 0xB7), (0xD7, 0xD7)]
punct = sorted(cp for cp in cmap if any(a <= cp <= b for a, b in PUNCT_RANGES))
cmap -= set(punct)

cjk = sorted(
    (cp for cp in cmap if cp >= 0x80 and big5_key(cp) is not None and 0x4E00 <= cp <= 0x9FFF),
    key=big5_key,
)
seen = set(cjk)
rest = sorted(cp for cp in cmap if cp not in seen)
# Small non-CJK glyphs (Latin, punctuation, symbols, kana, bopomofo) in one chunk each by codepoint order.
groups = [punct] if punct else []
groups += [cjk[i : i + CHUNK] for i in range(0, len(cjk), CHUNK)]
groups += [rest[i : i + CHUNK * 2] for i in range(0, len(rest), CHUNK * 2)]

def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c
            continue
        out.append((start, prev))
        start = prev = c
    out.append((start, prev))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in out)

for old in OUT.glob("*.woff2"):
    old.unlink()

rules = []
for i, g in enumerate(groups):
    name = f"{FAMILY}-{i:02d}.woff2"
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = [1, 2, 3, 4, 6]
    opts.notdef_outline = True
    opts.hinting = False
    font = subset.load_font(str(SRC), opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=g)
    s.subset(font)
    subset.save_font(font, str(OUT / name), opts)
    rules.append(
        f'@font-face {{\n  font-family: "{FAMILY}";\n  font-style: normal;\n  font-weight: 400;\n'
        f"  font-display: swap;\n  src: url(./fonts/{name}) format(\"woff2\");\n"
        f"  unicode-range: {ranges(g)};\n}}\n"
    )

header = (
    f"/* Generated by scripts/split-fonts.py from jf open-huninn (SIL OFL 1.1, see fonts/LICENSE-jf-openhuninn.txt). Do not edit. */\n"
)
(ROOT / "src/fonts.css").write_text(header + "\n".join(rules))
total = sum(p.stat().st_size for p in OUT.glob("*.woff2"))
print(f"{len(groups)} subsets, {total} bytes")
