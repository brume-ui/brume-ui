import { component } from './component';
import { font, radius, shadow, spacingBase } from './primitives';
import { derived, semantic } from './semantic';

type Mode = 'light' | 'dark';

const names = Object.keys(semantic) as (keyof typeof semantic)[];

function colorVars(mode: Mode, indent: string): string {
  return names
    .map(
      (n) =>
        `${indent}--br-${n}: ${mode === 'light' ? (derived[n] ?? semantic[n].light) : (derived[n] ?? semantic[n].dark)};`,
    )
    .join('\n');
}

function staticVars(indent: string): string {
  const lines = [
    ...Object.entries(radius).map(([k, v]) => `--br-radius-${k}: ${v};`),
    ...Object.entries(shadow).map(([k, v]) => `--br-shadow-${k}: ${v};`),
    `--br-font-sans: ${font.sans};`,
    `--br-spacing: ${spacingBase};`,
    ...Object.entries(component).map(([k, v]) => `--br-${k}: ${v};`),
  ];
  return lines.map((l) => `${indent}${l}`).join('\n');
}

export function buildTokensCss(): string {
  return `/* Generated by @herb09638/brume-tokens. Do not edit. */
:root {
  color-scheme: light;
${colorVars('light', '  ')}
${staticVars('  ')}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${colorVars('dark', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorVars('dark', '    ')}
  }
}
`;
}

export function buildThemeCss(): string {
  const colors = names.map((n) => `  --color-${n}: var(--br-${n});`).join('\n');
  const radii = Object.keys(radius)
    .map((k) => `  --radius-${k}: var(--br-radius-${k});`)
    .join('\n');
  const shadows = Object.keys(shadow)
    .map((k) => `  --shadow-${k}: var(--br-shadow-${k});`)
    .join('\n');
  return `/* Generated by @herb09638/brume-tokens. Do not edit. Import after tokens.css. */
@theme inline {
${colors}
${radii}
${shadows}
  --font-sans: ${font.sans};
  --spacing: ${spacingBase};
}
`;
}

export function buildTokensJson(): string {
  return `${JSON.stringify({ semantic, radius, shadow, font, spacing: spacingBase, component }, null, 2)}\n`;
}
